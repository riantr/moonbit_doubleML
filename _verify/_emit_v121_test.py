def lit(v):
    r = repr(float(v))
    if "e" in r and "." not in r.split("e")[0]:
        mant, exp = r.split("e")
        r = mant + ".0e" + exp
    return r


def flat(values, per_line=8, indent="    "):
    rows = []
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        sep = "," if i + per_line < len(values) else ""
        rows.append(indent + ", ".join(lit(v) for v in chunk) + sep)
    return rows


