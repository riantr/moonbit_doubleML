"""The GENERATOR and the file it generates must agree.

THE CLASS
=========
`ENGINEERING.md`, `README.mbt.md` and `moonbit_doubleML/README.mbt.md` are
GENERATED by `_verify/_r18_build_readme_1650.py`.  A document that is
generated has TWO copies of every claim: the one a reader opens and the one
the generator emits.  When they drift apart, the reader's copy is the one
that is published -- and the generator is the one that comes back on the next
rebuild.

ROUND 86 CAUGHT ONE
===================
Round 86's banner publications were spliced into the GENERATED file, and the
generator was left behind: it still published the pre-correction shift-map
numbers (**108350** mappings, **0** different) and it was missing four of the
round's publications.  A rebuild would have restored the stale numbers and
dropped four findings -- silently, because nothing compared the two.

WHAT THIS CHECK DOES
====================
It copies the tracked tree into a scratch directory, runs the builder THERE
(so the tree it measures is never rewritten), and compares the three outputs
with the tracked files, byte for byte.  It then proves the comparison BITES:
a builder with one byte changed produces a different file, and the check
reports it.
"""
import io
import os
import shutil
import subprocess
import sys
import tempfile

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILDER_REL = os.path.join("_verify", "_r18_build_readme_1650.py")
OUTPUTS = ["ENGINEERING.md", "README.mbt.md",
           os.path.join("moonbit_doubleML", "README.mbt.md")]

FAILS = []
NCHECK = 0


def check(label, ok, detail=""):
    global NCHECK
    NCHECK += 1
    if ok:
        print("  ok   %s" % label)
    else:
        print("  FAIL %s" % label)
        if detail:
            print("       %s" % detail)
        print("*** FAIL *** %s" % label)
        FAILS.append(label)


def read(path):
    with io.open(path, "rb") as fh:
        return fh.read()


def tracked_files():
    p = subprocess.run(["git", "-C", ROOT, "ls-files", "-z"],
                       capture_output=True)
    out = []
    for rel in p.stdout.split(b"\x00"):
        if rel:
            out.append(rel.decode("utf-8", errors="replace"))
    return out


def copy_tree(dest):
    """The tracked tree, copied.  The builder reads the tree it is given."""
    copied = 0
    for rel in tracked_files():
        src = os.path.join(ROOT, rel.replace("/", os.sep))
        dst = os.path.join(dest, rel.replace("/", os.sep))
        if not os.path.isfile(src):
            continue
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(src, dst)
        copied += 1
    return copied


def run_builder(scratch):
    env = dict(os.environ)
    gitdir = os.path.join(ROOT, ".git")
    if os.path.isdir(gitdir):
        env["GIT_DIR"] = gitdir
        env["GIT_WORK_TREE"] = scratch
    return subprocess.run(
        [sys.executable, "-X", "utf8",
         os.path.join(scratch, BUILDER_REL.replace("/", os.sep))],
        cwd=scratch, capture_output=True, text=True, encoding="utf-8",
        errors="replace", env=env, timeout=900)


def compare(scratch):
    """(label, ok, detail) for every generated file."""
    out = []
    for rel in OUTPUTS:
        made = os.path.join(scratch, rel.replace("/", os.sep))
        tracked = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.isfile(made):
            out.append((rel, False, "the builder did not write it"))
            continue
        if not os.path.isfile(tracked):
            out.append((rel, False, "the tree does not carry it"))
            continue
        a, b = read(made), read(tracked)
        if a == b:
            out.append((rel, True, "%d bytes, byte-identical" % len(a)))
        else:
            out.append((rel, False,
                        "the generator wrote %d bytes, the tree carries %d"
                        % (len(a), len(b))))
    return out


print("=" * 78)
print("the generator and the tree it generates")
print("=" * 78)

before = {rel: read(os.path.join(ROOT, rel.replace("/", os.sep)))
          for rel in OUTPUTS if os.path.isfile(
              os.path.join(ROOT, rel.replace("/", os.sep)))}

scratch = tempfile.mkdtemp(prefix="gen_sync_")
try:
    n = copy_tree(scratch)
    check("the tracked tree is copied into a scratch directory", n > 100,
          "%d file(s) copied" % n)

    p = run_builder(scratch)
    check("the builder runs in the scratch tree", p.returncode == 0,
          "exit %d: %s" % (p.returncode, (p.stderr or "")[-300:]))

    for rel in OUTPUTS:
        made = os.path.join(scratch, rel.replace("/", os.sep))
        check("the builder writes %s" % rel, os.path.isfile(made),
              "%s does not exist" % made)

    for rel, ok, detail in compare(scratch):
        check("%s: the generator's output is the file the tree carries" % rel,
              ok, detail)

    root_readme = os.path.join(ROOT, "README.mbt.md")
    shipped = os.path.join(ROOT, "moonbit_doubleML", "README.mbt.md")
    if os.path.isfile(root_readme) and os.path.isfile(shipped):
        check("the root README.mbt.md is byte-identical to the shipped copy",
              read(root_readme) == read(shipped))
    else:
        check("the root README.mbt.md is byte-identical to the shipped copy",
              False, "one of the two files is missing")

    # ---- the control arms: the comparison has to BITE --------------------
    gen = os.path.join(scratch, BUILDER_REL.replace("/", os.sep))
    src = read(gen).decode("utf-8", errors="replace")
    mutated = src.replace('LEDGER_HEAD = """', 'LEDGER_HEAD = """X', 1)
    if mutated == src:
        mutated = src.replace("ENGINEERING.md", "ENGINEERING.md ", 1)
    if mutated == src:
        check("CONTROL: a mutated builder produces a different file", False,
              "the builder's source could not be mutated")
    else:
        with io.open(gen, "w", encoding="utf-8", newline="") as fh:
            fh.write(mutated)
        p2 = run_builder(scratch)
        made = os.path.join(scratch, "ENGINEERING.md")
        tracked = os.path.join(ROOT, "ENGINEERING.md")
        differs = (p2.returncode == 0 and os.path.isfile(made)
                   and read(made) != read(tracked))
        check("CONTROL: a mutated builder produces a different file", differs,
              "the mutated builder's output was not detected as different")

    # the second arm: a mutated OUTPUT must be rejected
    made = os.path.join(scratch, "ENGINEERING.md")
    tracked = os.path.join(ROOT, "ENGINEERING.md")
    if os.path.isfile(made) and os.path.isfile(tracked):
        with io.open(made, "ab") as fh:
            fh.write(b"X")
        res = compare(scratch)
        eng = [r for r in res if r[0] == "ENGINEERING.md"]
        rejected = bool(eng) and not eng[0][1]
        check("CONTROL: a mutated output is rejected", rejected,
              "the mutated output was not detected")
    else:
        check("CONTROL: a mutated output is rejected", False,
              "the scratch ENGINEERING.md is missing")
finally:
    shutil.rmtree(scratch, ignore_errors=True)
    check("the scratch directory is removed", not os.path.isdir(scratch))

after = {rel: read(os.path.join(ROOT, rel.replace("/", os.sep)))
         for rel in OUTPUTS if os.path.isfile(
             os.path.join(ROOT, rel.replace("/", os.sep)))}
check("this check does not modify the tree", before == after)

print()
print("=" * 78)
print("%d checks, %d failed" % (NCHECK, len(FAILS)))
if FAILS:
    print("*** FAIL ***")
    for f in FAILS:
        print("  - %s" % f)
print("=" * 78)
sys.exit(1 if FAILS else 0)
