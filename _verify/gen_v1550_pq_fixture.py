"""Emit a DoubleMLPQ fixture as a generated MoonBit file + upstream answers.

This closes the gap left by `_verify/gen_v1550_pq_oracle.py`: that script
measured how far upstream's `normalize_ipw=True` and `False` branches are
APART, but never established which branch the MOONBIT PORT sits on.

Method (the `_verify/gen_v119_oracle.py` pattern, v0.119.0):

  * Python builds the fixture and runs upstream's own DoubleMLPQ twice,
    with splits pinned and reproducibility verified.
  * Python WRITES the fixture into a generated `.mbt` file as float literals.
  * The MoonBit side reads those literals and fits the port's DoubleMLPQ on
    the identical arrays.

The MoonBit side therefore never tries to reproduce NumPy's PCG64, which
would be a guess dressed up as a port.

Choosing b: the fixture has to DISCRIMINATE between the two branches, so the
gap between them has to be large relative to fold-assignment differences.
At b=0.5 the gap is 3.8e-13, which cannot discriminate anything. b=1.5 and
b=4.0 are emitted.

Run from the repo root:
    python _verify/gen_v1550_pq_fixture.py
"""

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(os.path.dirname(HERE), "moonbit_doubleML")
sys.path.insert(0, os.path.join(HERE, "_upstream_ps", "doubleml-0.11.4"))

from doubleml import DoubleMLData, DoubleMLPQ  # noqa: E402
from doubleml.utils.resampling import DoubleMLResampling  # noqa: E402
from sklearn.linear_model import LogisticRegression  # noqa: E402

N = 1000
SEED = 3141
QUANTILE = 0.5
N_FOLDS = 2
BS = [1.5, 4.0]


def dgp(n, seed, b):
    rng = np.random.default_rng(seed)
    x = rng.normal(size=(n, 1))
    ps = 1.0 / (1.0 + np.exp(-(0.5 + b * x.ravel())))
    d = (rng.uniform(size=n) < ps).astype(float)
    y = 1.0 * d + 0.5 * x.ravel() + rng.normal(size=n) * 0.5
    return x.ravel(), y, d, ps


def scalar(v):
    return float(np.asarray(v).ravel()[0])


def upstream(x, y, d, b):
    dd = DoubleMLData(pd.DataFrame({"X1": x, "y": y, "d": d}), "y", "d")

    def make(norm):
        return DoubleMLPQ(
            dd,
            LogisticRegression(),
            LogisticRegression(),
            treatment=1,
            quantile=QUANTILE,
            n_folds=N_FOLDS,
            n_rep=1,
            normalize_ipw=norm,
        )

    smpls = DoubleMLResampling(
        n_folds=N_FOLDS, n_rep=1, n_obs=len(y), stratify=None
    ).split_samples()

    def pinned(norm):
        e = make(norm)
        e.set_sample_splitting(smpls)
        return e

    # Verify the pinned path is reproducible BEFORE trusting any comparison.
    r1, r2 = pinned(True), pinned(True)
    r1.fit()
    r2.fit()
    if scalar(r1.coef) != scalar(r2.coef):
        raise RuntimeError(f"b={b}: pinned splits are not reproducible")

    t, f = pinned(True), pinned(False)
    t.fit()
    f.fit()
    return scalar(t.coef), scalar(t.se), scalar(f.coef), scalar(f.se)


def emit(path, name, x, y, d):
    def arr(name, values, per_line=4):
        lines = [f"pub fn {name}() -> Array[Double] {{"]
        lines.append("  [")
        for i in range(0, len(values), per_line):
            chunk = ", ".join(repr(float(v)) for v in values[i : i + per_line])
            lines.append(f"    {chunk},")
        lines.append("  ]")
        lines.append("}")
        return "\n".join(lines)

    body = f"""// GENERATED by _verify/gen_v1550_pq_fixture.py -- do not edit.
//
// n={len(y)}, seed={SEED}, quantile={QUANTILE}, n_folds={N_FOLDS}, one feature.
// Upstream answers on these EXACT arrays are printed by the generator and
// compared in probe_v1550ok5_test.mbt.

{arr(f"{name}_x_flat", x)}

{arr(f"{name}_y", y)}

{arr(f"{name}_d", d)}

pub fn {name}() -> (Matrix, Array[Double], Array[Double]) {{
  (
    Matrix::from_array({name}_x_flat(), {len(x)}, 1),
    {name}_y(),
    {name}_d(),
  )
}}
"""
    with open(path, "w", newline="\n") as f:
        f.write(body)


def main():
    results = {}
    for b in BS:
        x, y, d, ps = dgp(N, SEED, b)
        ct, st, cf, sf = upstream(x, y, d, b)
        results[b] = (ct, st, cf, sf)
        out = os.path.join(PKG, f"v1550_fixture_b{str(b).replace('.', '_')}.mbt")
        emit(out, f"v1550_dgp_b{str(b).replace('.', '_')}", x, y, d)
        print(f"b={b}: wrote {os.path.basename(out)}")
        print(f"   ps range = [{ps.min():.4f}, {ps.max():.4f}]")
        print(f"   upstream normalize_ipw=True  coef={ct!r} se={st!r}")
        print(f"   upstream normalize_ipw=False coef={cf!r} se={sf!r}")
        print(f"   |gap| = {abs(ct - cf):.6e}")
        print()
    print("PORT_SIDE_EXPECTATIONS (probe_v1550ok5_test.mbt should print these):")
    for b in BS:
        ct, st, cf, sf = results[b]
        print(f"  b={b}  upstream_true={ct!r}  upstream_false={cf!r}")


if __name__ == "__main__":
    main()