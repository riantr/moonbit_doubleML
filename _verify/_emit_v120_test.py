"""Emit moonbit_doubleML/expand_v120_test.mbt from _v120_golden.json.

The golden is produced by `gen_v120_oracle.py`, which calls scikit-learn
1.9.0. This script does NOT refit anything -- it only renders what the
golden already contains, plus the gate logic below.

Why a generator emits the test file rather than just its data: a gate
whose arrays can drift from the oracle it is compared against is not a
gate. v0.119.0 shipped a one-character formula error that survived 890
internal tests; the only thing that caught it was an external oracle
called on the same arrays. That property is only worth anything if the
two sides are guaranteed to share the arrays.
"""
