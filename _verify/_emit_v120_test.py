def lit(v):
    r = repr(float(v))
    # MoonBit will not lex a bare `1e-10`; it wants `1.0e-10`.
    if "e" in r and "." not in r.split("e")[0]:
        mant, exp = r.split("e")
        r = mant + ".0e" + exp
    return r


def flat_list(values, per_line=8):
    """A flat numeric array, wrapped into continuation rows."""
    rows = ["  ["]
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        sep = "," if i + per_line < len(values) else ""
        rows.append("    " + ", ".join(lit(v) for v in chunk) + sep)
    rows.append("  ]")
    return rows


