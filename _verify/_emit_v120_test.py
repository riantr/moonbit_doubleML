def _rewrite_asserts(text):
    key = "assert_true("
    parts = []
    i = 0
    while True:
        j = text.find(key, i)
        if j < 0:
            parts.append(text[i:])
            break
        parts.append(text[i:j])
        k = j + len(key)
        depth = 1
        while depth > 0:
            ch = text[k]
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            k += 1
        expr = text[j + len(key):k - 1]
        parts.append('v120_expect(%s, "%s")' % (expr, _label_for(expr)))
        i = k
    return "".join(parts)


