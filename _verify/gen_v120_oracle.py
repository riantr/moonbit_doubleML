"""v0.120.0 ORACLE: emit the regularised-learner fixtures.

The arrays here are EMITTED by this script and pasted into
`_verify/_v120_golden.json`; they are never regenerated by a test.
Reproducing NumPy's PCG64 inside MoonBit would be a guess dressed as
a port, so the fixture arrays are treated as opaque input data and the
reference values are what sklearn itself computed on those arrays.

What is recorded per fixture:
    coef / intercept  -- sklearn 1.9.0's own output
    objective         -- F(coef) under the solver's normalisation, which
                        is what the MoonBit gate compares (the
                        objective is flat at the optimum; the
                        coefficient vector is not)
    gap               -- sklearn's own reported duality gap
    n_iter            -- sklearn's sweep count

Tolerances in the MoonBit gate are DERIVED from the worst numbers this
file prints, not chosen to make a test pass.
"""
import json
import os
import warnings

import numpy as np
import sklearn
from sklearn.linear_model import ElasticNet, Ridge

warnings.simplefilter("ignore")
assert sklearn.__version__ == "1.9.0", sklearn.__version__

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "_v120_golden.json")

# tol/max_iter used for BOTH sides. sklearn's default tol=1e-4 stops far
# too early for two different stopping rules to be compared meaningfully
# (probe: coefficient gaps up to 5.1e-1 at tol=1e-4, 8.8e-4 at 1e-10).
TOL = 1e-10
MAX_ITER = 1000000


def objective(coef, X, y, w, alpha, lr):
    n = X.shape[0]
    wt = np.ones(n) if w is None else w * (n / w.sum())
    xm = np.average(X, 0, weights=w) if w is not None else X.mean(0)
    ym = np.average(y, weights=w) if w is not None else y.mean()
    r = (y - ym) - (X - xm) @ coef
    return float(0.5 * (wt @ (r * r)) / n
                 + alpha * lr * float(np.abs(coef).sum())
                 + 0.5 * alpha * (1 - lr) * float((coef * coef).sum()))


def kkt_gap(coef, X, y, w, alpha, lr):
    """max(0, max_j |(1/n)x_j'r + alpha(1-lr)w_j| - alpha*lr) * ||w||_1

    This is the textbook Lasso duality gap with the L2 term folded in.
    Sign is taken on the SMOOTH gradient only; putting |.| around the
    whole thing (as probe 5 did) reports a gap for a point that is
    actually optimal.
    """
    n = X.shape[0]
    wt = np.ones(n) if w is None else w * (n / w.sum())
    xm = np.average(X, 0, weights=w) if w is not None else X.mean(0)
    ym = np.average(y, weights=w) if w is not None else y.mean()
    r = (y - ym) - (X - xm) @ coef
    smooth = -(X - xm).T @ (wt * r) / n + alpha * (1 - lr) * coef
    return float(max(0.0, float(np.abs(smooth).max()) - alpha * lr)
                 * float(np.abs(coef).sum()))


def ridge_objective(coef, intercept, X, y, w, alpha):
    n = X.shape[0]
    wt = np.ones(n) if w is None else w
    xm = np.average(X, 0, weights=w) if w is not None else X.mean(0)
    ym = np.average(y, weights=w) if w is not None else y.mean()
    r = (y - ym) - (X - xm) @ coef
    return float(0.5 * (wt @ (r * r)) + 0.5 * alpha * float((coef * coef).sum()))


# --------------------------------------------------------------------------
# fixtures
# --------------------------------------------------------------------------
rng = np.random.default_rng(20261009)
FIX = []

X = rng.normal(size=(30, 3))
y = 2.0 + X @ np.array([1.0, -0.5, 0.25]) + rng.normal(size=30) * 0.2
FIX.append(dict(name="f0_tiny", X=X, y=y, w=None,
                desc="well-conditioned 30x3, no weights"))

X = rng.normal(size=(40, 3))
X[:, 1] = 1.7 * X[:, 0] - 0.3 * rng.normal(size=40)
y = 1.5 + 2 * X[:, 0] - 0.8 * X[:, 1] + 0.5 * X[:, 2] + rng.normal(size=40) * 0.3
FIX.append(dict(name="f1_collinear", X=X, y=y, w=None,
                desc="near-collinear pair; exercises the centred solver"))

X = rng.normal(size=(8, 12))
y = rng.normal(size=8)
FIX.append(dict(name="f2_p_gt_n", X=X, y=y, w=None,
                desc="p > n: a cross-fit fold smaller than the feature count"))

X = rng.normal(size=(60, 5))
X[:, 1] = 1.5 * X[:, 0]
y = 1.0 + X @ np.array([2.0, -1.0, 0.3, 0.0, 1.2]) + rng.normal(size=60) * 0.5
FIX.append(dict(name="f3_warm", X=X, y=y, w=None,
                desc="exact duplicate column: rank-deficient"))

X = rng.normal(size=(60, 5))
y = 1.0 + X @ np.array([2.0, -1.0, 0.3, 0.0, 1.2]) + rng.normal(size=60) * 0.5
FIX.append(dict(name="f4_weighted", X=X, y=y, w=rng.uniform(0.3, 3.0, size=60),
                desc="non-uniform sample_weight"))

n2, p2 = 300, 60
X = rng.normal(size=(n2, p2))
X[:, 1] = X[:, 0] + 1e-7 * rng.normal(size=n2)
X[:, 2] = X[:, 0] * 1.0001
X[:, 3] = 2 * X[:, 0]
beta = np.zeros(p2)
sel = rng.random(p2) < 0.3
beta[sel] = rng.normal(size=int(sel.sum()))
y = X @ beta + rng.normal(size=n2) * 0.5
FIX.append(dict(name="f5_hard", X=X, y=y, w=None,
                desc="300x60 with four collinear columns"))

X = rng.normal(size=(50, 4)) * 1e3 + 5e4
y = 1e5 + X @ np.array([1.0, -2.0, 0.1, 3.0]) + rng.normal(size=50) * 10.0
FIX.append(dict(name="f6_scaled", X=X, y=y, w=None,
                desc="huge offset and scale: centring must do real work"))

# --------------------------------------------------------------------------
# emit
# --------------------------------------------------------------------------
golden = {
    "source": "scikit-learn==%s, numpy==%s" % (sklearn.__version__, np.__version__),
    "tol": TOL,
    "max_iter": MAX_ITER,
    "fixtures": [],
}

worst_ridge = 0.0
worst_obj_rel = 0.0
worst_zero_mismatch = 0

for f in FIX:
    rec = {
        "name": f["name"],
        "desc": f["desc"],
        "n": int(f["X"].shape[0]),
        "p": int(f["X"].shape[1]),
        "X": [[float(v) for v in row] for row in f["X"]],
        "y": [float(v) for v in f["y"]],
        "w": None if f["w"] is None else [float(v) for v in f["w"]],
        "ridge": [],
        "enet": [],
    }

    for alpha in (0.05, 0.7, 5.0):
        m = Ridge(alpha=alpha, fit_intercept=True).fit(f["X"], f["y"],
                                                        sample_weight=f["w"])
        rec["ridge"].append({
            "alpha": alpha,
            "coef": [float(v) for v in m.coef_],
            "intercept": float(m.intercept_),
            "objective": ridge_objective(m.coef_, float(m.intercept_),
                                         f["X"], f["y"], f["w"], alpha),
        })

    for alpha, lr in ((0.5, 1.0), (0.05, 1.0), (0.1, 0.5), (0.2, 0.25), (0.02, 0.75)):
        m = ElasticNet(alpha=alpha, l1_ratio=lr, fit_intercept=True,
                       tol=TOL, max_iter=MAX_ITER).fit(f["X"], f["y"],
                                                       sample_weight=f["w"])
        coef = np.asarray(m.coef_, dtype=float)
        rec["enet"].append({
            "alpha": alpha,
            "l1_ratio": lr,
            "tol": TOL,
            "max_iter": MAX_ITER,
            "coef": [float(v) for v in coef],
            "intercept": float(m.intercept_),
            "objective": objective(coef, f["X"], f["y"], f["w"], alpha, lr),
            "gap": kkt_gap(coef, f["X"], f["y"], f["w"], alpha, lr),
            "nnz": int((coef != 0.0).sum()),
            "n_iter": int(m.n_iter_),
        })

    golden["fixtures"].append(rec)

# --------------------------------------------------------------------------
# report: the numbers the MoonBit tolerances are derived from
# --------------------------------------------------------------------------
print("=" * 92)
print("sklearn %s / numpy %s, tol=%g max_iter=%d" % (sklearn.__version__,
                                                      np.__version__, TOL, MAX_ITER))
print("=" * 92)
print("%-14s %6s %8s %14s %10s %14s" % ("fixture", "alpha", "lr", "objective",
                                        "gap", "n_iter"))
for f, rec in zip(FIX, golden["fixtures"]):
    for e in rec["enet"]:
        print("%-14s %6g %8g %14.8e %10.2e %14d" % (
            rec["name"], e["alpha"], e["l1_ratio"], e["objective"], e["gap"], e["n_iter"]))

print()
print("cross-check identity: ElasticNet(l1_ratio=0, alpha=a) == Ridge(alpha=a*n)")
for f, rec in zip(FIX, golden["fixtures"]):
    n = rec["n"]
    for a in (0.05, 0.7, 5.0):
        e = ElasticNet(alpha=a, l1_ratio=0.0, fit_intercept=True,
                       tol=TOL, max_iter=MAX_ITER).fit(f["X"], f["y"], sample_weight=f["w"])
        r = Ridge(alpha=a * n).fit(f["X"], f["y"], sample_weight=f["w"])
        d = float(np.max(np.abs(np.concatenate([e.coef_, [e.intercept_]])
                                   - np.concatenate([r.coef_, [float(r.intercept_)]]))))
        worst_ridge = max(worst_ridge, d)
        print("  %-14s a=%-5g  max|EN0 - Ridge(a*n)| = %.3e" % (rec["name"], a, d))
print("  >>> WORST identity gap = %.3e" % worst_ridge)

print()
print("cross-check identity: Lasso(alpha) == ElasticNet(alpha, l1_ratio=1)")
worst_l = 0.0
for f, rec in zip(FIX, golden["fixtures"]):
    for a in (0.05, 0.5, 5.0):
        from sklearn.linear_model import Lasso
        ls = Lasso(alpha=a, tol=TOL, max_iter=MAX_ITER).fit(f["X"], f["y"], sample_weight=f["w"])
        en = ElasticNet(alpha=a, l1_ratio=1.0, fit_intercept=True,
                        tol=TOL, max_iter=MAX_ITER).fit(f["X"], f["y"], sample_weight=f["w"])
        d = float(np.max(np.abs(np.concatenate([ls.coef_, [ls.intercept_]])
                                   - np.concatenate([en.coef_, [en.intercept_]]))))
        worst_l = max(worst_l, d)
print("  >>> WORST Lasso == ElasticNet(l1_ratio=1) gap = %.3e" % worst_l)

print()
print("scale invariance: Lasso(sw) vs Lasso(17*sw)")
worst_s = 0.0
for f in FIX:
    if f["w"] is None:
        continue
    w17 = f["w"] * 17.0
    a = ElasticNet(alpha=0.1, l1_ratio=0.5, tol=TOL, max_iter=MAX_ITER).fit(
        f["X"], f["y"], sample_weight=f["w"])
    b = ElasticNet(alpha=0.1, l1_ratio=0.5, tol=TOL, max_iter=MAX_ITER).fit(
        f["X"], f["y"], sample_weight=w17)
    worst_s = max(worst_s, float(np.max(np.abs(a.coef_ - b.coef_))))
print("  >>> WORST scale-invariance gap = %.3e" % worst_s)

with open(OUT, "w", encoding="utf-8") as fh:
    json.dump(golden, fh, indent=1)
print()
print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))