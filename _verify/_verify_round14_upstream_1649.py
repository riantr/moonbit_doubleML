# 7. the Pilot 2 error count, derived from the tracked log
# ---------------------------------------------------------------------------
def group_pilot2():
    p = os.path.join(ROOT, "_prove_pilot2_error.txt")
    if not check("Pilot 2 error file present", os.path.exists(p)):
        return
    check("Pilot 2 error file tracked", tracked("_prove_pilot2_error.txt"))
    txt = open(p, encoding="utf-8", errors="replace").read()
    # Count the REAL moonc error blocks.  The captured log is a PowerShell
    # transcript, so the first moon error appears three times: as
    # "moon : Error: [4207]" (the stderr prefix), inside the
    # "+ CategoryInfo ... (Error: [4207]...)" wrapper, and -- if the run were
    # not PowerShell -- on its own line.  The "+ CategoryInfo" mention is a
    # formatting duplicate and is not a second error.
    plain = len(re.findall(r"^Error: \[4207\]", txt, re.M))
    prefixed = len(re.findall(r"^\ufeff?moon : Error: \[4207\]", txt, re.M))
    real = plain + prefixed
    check("Pilot 2 log has 8 real moonc error blocks", real == 8,
          "found %d (%d plain + %d prefixed); the transcript mentions the "
          "string %d times in total"
          % (real, plain, prefixed, txt.count("Error: [4207]")))
    for rel in RECORDS:
        p2 = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p2):
            continue
        t = read(rel)
        for m in re.finditer(r"produced (\d+) distinct", t):
            check("%s: 'N distinct errors' matches the log" % os.path.basename(rel),
                  int(m.group(1)) == real, "doc=%s log=%d" % (m.group(1), real))


