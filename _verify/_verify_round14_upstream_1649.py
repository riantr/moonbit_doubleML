# 6. the re-audit harness
# ---------------------------------------------------------------------------
def group_reaudit():
    for rel in ("_verify/upstream_prove_1649/README.md",
                "_verify/upstream_prove_1649/run_reaudit.py",
                "_verify/upstream_prove_1649/summarise.py",
                "_verify/upstream_prove_1649/.gitignore"):
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        check("re-audit artefact exists: %s" % os.path.basename(rel),
              os.path.exists(p))
        check("re-audit artefact tracked: %s" % os.path.basename(rel),
              tracked(rel))
    cdir = os.path.join(REAUDIT, "cases")
    cases = sorted(d for d in os.listdir(cdir)
                   if os.path.isdir(os.path.join(cdir, d))) \
        if os.path.isdir(cdir) else []
    check("re-audit has cases", len(cases) >= 9, "%d cases" % len(cases))
    for c in cases:
        for f in ("case.mbt", "moon.mod", "moon.pkg"):
            check("case %s has %s" % (c, f),
                  os.path.exists(os.path.join(cdir, c, f)))
        log = os.path.join(REAUDIT, "out", c + ".log")
        check("case %s has a log" % c, os.path.exists(log))
    # the README table must match the LOGS
    rp = os.path.join(REAUDIT, "README.md")
    if not os.path.exists(rp):
        check("re-audit README present", False)
        return
    txt = open(rp, encoding="utf-8").read()
    rows = dict((m.group(1), int(m.group(2)))
                for m in re.finditer(r"^\|\s*`([A-Za-z0-9_]+)`\s*\|\s*(\d+)\s*\|", txt,
                                     re.M))
    for c in cases:
        log = os.path.join(REAUDIT, "out", c + ".log")
        if not os.path.exists(log):
            continue
        n4207 = open(log, encoding="utf-8", errors="replace").read().count(
            "Error: [4207]")
        stated = rows.get(c)
        check("re-audit README table matches the log: %s" % c,
              stated is not None and stated == n4207,
              "log=%d table=%s" % (n4207, stated))
    # the controls are declared by the HARNESS, not by the prose
    runner = os.path.join(REAUDIT, "run_reaudit.py")
    controls = []
    if os.path.exists(runner):
        src = open(runner, encoding="utf-8", errors="replace").read()
        m = re.search(r"^CONTROLS\s*=\s*\[([^\]]*)\]", src, re.M)
        if m:
            controls = re.findall(r'"([^"]+)"', m.group(1))
    check("the harness declares its control cases", len(controls) >= 2,
          str(controls))
    for c in controls:
        log = os.path.join(REAUDIT, "out", c + ".log")
        if not os.path.exists(log):
            check("control case has a log: %s" % c, False)
            continue
        t = open(log, encoding="utf-8", errors="replace").read()
        check("control case has 0 frontend errors: %s" % c,
              "Error: [4207]" not in t)
    check("re-audit README states the run commands",
          "python run_reaudit.py" in txt and "python summarise.py" in txt)
    check("re-audit README states the platform limitation",
          "Unix.Unix_error" in txt and "Windows" in txt)


