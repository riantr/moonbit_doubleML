# 10. the README against the reference pages' acceptance bar
# ---------------------------------------------------------------------------
def group_readme_bar():
    rp = os.path.join(ROOT, "README.mbt.md")
    if not check("README present", os.path.exists(rp)):
        return
    txt = open(rp, encoding="utf-8").read()
    check("README states a 'not covered / not claimed' section",
          "Still not covered" in txt or "not claimed" in txt)
    check("README lists the exact reproduction commands",
          "moon test --target native --deny-warn" in txt
          and "moon run examples/main" in txt)
    # the toolchain row must name the installed moon
    m = re.search(r"^\|\s*Toolchain\s*\|\s*`moon ([0-9.]+)`", txt, re.M)
    if not check("README Status table has a Toolchain row", bool(m)):
        return
    stated = m.group(1)
    r = subprocess.run(["moon", "--version"], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    inst = re.search(r"moon\s+([0-9.]+)", r.stdout)
    check("README Toolchain row names the installed moon",
          bool(inst) and inst.group(1) == stated,
          "README=%s installed=%s" % (stated, inst.group(1) if inst else "?"))


def main():
    print("=" * 78)
    print("ROUND 14 VERIFIER -- upstream records + README headline")
    print("root: %s" % ROOT)
    print("=" * 78)
    group_records()
    est = derived_estimator_count()
    group_estimator_count(est)
    group_paths()
    group_mojibake()
    group_witnesses()
    group_reaudit()
    group_pilot2()
    group_line_pointers()
    group_retractions()
    group_readme_bar()

    fails = [r for r in results if not r[1]]
    print()
    print("=" * 78)
    print("checks: %d   failures: %d" % (len(results), len(fails)))
    print("=" * 78)
    for n, _, d in fails:
        print("  FAIL  %s  %s" % (n, d))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
