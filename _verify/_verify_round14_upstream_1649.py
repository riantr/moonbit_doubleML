# 8. the kfold.mbt line pointers, resolved against the v0.52.0 revision
# ---------------------------------------------------------------------------
def group_line_pointers():
    tag = "v0.52.0"
    kfold = git("show", tag + ":kfold.mbt")
    if not kfold:
        check("kfold.mbt readable at %s" % tag, False)
        return
    lines = kfold.split("\n")
    check("kfold.mbt at %s is 657 lines" % tag, len(lines) == 657,
          "got %d" % len(lines))
    cited = set()
    for rel in RECORDS:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        t = read(rel)
        for m in re.finditer(r"`kfold\.mbt:([0-9,\- ]+)`", t):
            for part in m.group(1).replace(" ", "").split(","):
                if "-" in part:
                    a, b = part.split("-")
                    try:
                        cited.update(range(int(a), int(b) + 1))
                    except ValueError:
                        pass
                elif part.isdigit():
                    cited.add(int(part))
    over = sorted(n for n in cited if n > len(lines))
    check("every cited kfold.mbt line exists at %s" % tag, not over,
          "%d distinct lines cited, %d out of range" % (len(cited), len(over)))
    # the C-style claim: lines 331, 338, 342 are C-style range loops
    cstyle = [n for n in (331, 338, 342)
              if n <= len(lines)
              and re.search(r"for\s+\w+\s*=\s*0;", lines[n - 1])]
    check("kfold.mbt:331,338,342 are C-style range at %s" % tag,
          len(cstyle) == 3, "matched %s" % cstyle)
    # the try/catch shim at 266-274
    shim = [n for n in range(266, 275) if n <= len(lines)
            and ("try {" in lines[n - 1] or "catch {" in lines[n - 1]
                 or "require(" in lines[n - 1]
                 or "PreconditionError" in lines[n - 1]
                 or "abort(" in lines[n - 1])]
    check("kfold.mbt:266-274 is the try/catch shim at %s" % tag,
          len(shim) >= 7, "matched %d of 9 lines" % len(shim))


