results = []


def check(name, ok, detail=""):
    results.append((name, bool(ok), detail))
    print("%s  %-62s %s" % ("PASS" if ok else "FAIL", name, detail))
    return ok


def git(*args):
    r = subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True,
                       text=True, encoding="utf-8", errors="replace")
    return r.stdout


def tracked(rel):
    return bool(git("ls-files", "--", rel).strip())


def read(rel):
    with open(os.path.join(ROOT, rel.replace("/", os.sep)), encoding="utf-8",
             errors="replace") as f:
        return f.read()


def paragraphs(text):
    """[(start_line, end_line, block_text), ...] -- maximal non-blank runs."""
    out, cur, start = [], [], 1
    for i, ln in enumerate(text.split("\n"), 1):
        if ln.strip():
            if not cur:
                start = i
            cur.append(ln)
        else:
            if cur:
                out.append((start, i - 1, "\n".join(cur)))
                cur = []
    if cur:
        out.append((start, start + len(cur) - 1, "\n".join(cur)))
    return out


def para_at(paras, line):
    for s, e, b in paras:
        if s <= line <= e:
            return b
    return ""


