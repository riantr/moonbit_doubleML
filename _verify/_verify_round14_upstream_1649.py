# 9. the claims that are now false must not survive unmarked
# ---------------------------------------------------------------------------
def group_retractions():
    for rel in RECORDS:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        t = read(rel)
        name = os.path.basename(rel)
        check("%s: no 'remain tracked' claim" % name, "remain tracked" not in t)
        check("%s: no 'preserved sibling' claim" % name,
              "preserved sibling" not in t)
        check("%s: the local-only status of the audit artefacts is stated" % name,
              ("local-only" in t) or ("git-ignored" in t)
              or ("never committed" in t) or ("not in the repository" in t)
              or ("not obtainable" in t))
    # the three files whose claims changed must carry a re-audit correction
    for rel, needle in (
        ("_verify/UPSTREAM_ISSUE_03_raise_in_body.md", "A3"),
        ("_verify/UPSTREAM_ISSUE_04_foreach.md", "A4"),
        ("_verify/UPSTREAM_BLOCKERS.md", "A3"),
    ):
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        t = read(p)
        check("%s: carries a re-audit correction" % os.path.basename(rel),
              "Re-audit, 2026-10-20" in t)
        check("%s: the obsolete finding is named" % os.path.basename(rel),
              needle in t)
    # ISSUE_04's "workaround (verified)" must be marked as no longer holding
    p = os.path.join(ROOT, "_verify/UPSTREAM_ISSUE_04_foreach.md")
    if os.path.exists(p):
        t = read(p)
        check("ISSUE_04: the 'workaround (verified)' snippet is retracted",
              "no longer" in t and "b4c_style_control" in t)
        check("ISSUE_04: the `for x in 0..<n` claim is retracted",
              "b4r_range_foreach" in t)


