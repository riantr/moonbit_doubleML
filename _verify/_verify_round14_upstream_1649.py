# 5. the Bucket 3 witness must actually contain a raise
# ---------------------------------------------------------------------------
def group_witnesses():
    """The Bucket 3 reproducer the records cite must actually contain a raise.

    The records may cite a path that does NOT contain a raise, provided the
    record says so -- that is how a retracted witness is documented.  What
    must not survive is a record that cites a wrong file without saying so.
    """
    cited = {}
    for rel in RECORDS:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        txt = read(rel)
        paras = paragraphs(txt)
        for m in re.finditer(r"`([^`\n]*raise_test\.mbt)`", txt):
            c = m.group(1).replace("moonbit_doubleML/", "")
            line = txt[:m.start()].count("\n") + 1
            para = para_at(paras, line)
            cited.setdefault(c, []).append((rel, para))
    check("a Bucket 3 reproducer path is cited", bool(cited),
          "cited: %s" % sorted(cited))
    good = []
    for c, uses in sorted(cited.items()):
        p = os.path.join(ROOT, c.replace("/", os.sep))
        if not os.path.exists(p):
            check("cited Bucket 3 witness exists: %s" % c, False)
            continue
        src = open(p, encoding="utf-8", errors="replace").read()
        has_raise = "raise " in src and "suberror" in src
        is_double = "Double" in src
        if has_raise and not is_double:
            good.append(c)
            check("cited Bucket 3 witness contains a raise: %s" % c, True)
        else:
            # a wrong witness is only acceptable if the record says it is one
            marks = ("does not contain", "does not hold", "Bucket 2",
                     "not the reproducer", "wrong")
            marked = all(any(mk in p2 for mk in marks) for _, p2 in uses)
            unmarked = [rel for rel, p2 in uses
                        if not any(mk in p2 for mk in marks)]
            check("wrong Bucket 3 witness is marked as such: %s" % c, marked,
                  "raise=%s double=%s unmarked_in=%s"
                  % (has_raise, is_double, unmarked))
    check("at least one cited Bucket 3 witness really has a raise", bool(good),
          "good: %s" % good)
    # the Bucket 2 witness must be a Double source
    b2 = os.path.join(VD, "audit-bucket2-double", "double_cmp.mbt")
    if os.path.exists(b2):
        src = open(b2, encoding="utf-8", errors="replace").read()
        check("Bucket 2 witness is a Double source",
              "Double" in src and "1.5" in src)
    else:
        check("Bucket 2 witness present", False, b2)


