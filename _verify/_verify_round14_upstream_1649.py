# 3. path promises
# ---------------------------------------------------------------------------
TOKEN_RE = re.compile(r"`([^`\n]+)`")

# A token is a PATH PROMISE only if it could plausibly name a file in this
# repository.  Code identifiers look similar but are not paths: `arr.length()`,
# `@random.Rand::chacha8`, `Fold.train_idx`, `1.5`, `v0.52.0`.  The rule
# below is deliberately narrow -- a false positive costs a reader's trust in
# the whole check, and a false negative costs one broken promise.
PATH_EXTS = (".md", ".mbt", ".mbtp", ".log", ".csv", ".txt", ".json", ".mlw",
             ".yaml", ".yml", ".sh", ".ps1")


def path_like(tok):
    if not tok or " " in tok or "|" in tok:
        return False
    if any(c in tok for c in "*?[]{}()"):
        return False
    if ":" in tok:          # `file:line` pointers, `ns::symbol`, `v0.52.0`
        return False
    if tok.startswith(("http", "<", "#", "@")):
        return False
    norm = tok.replace("\\", "/")
    if "/" in norm:
        # a directory or a file path: only if the last segment has a
        # plausible file extension, or the whole thing looks like a dir
        last = norm.rstrip("/").split("/")[-1]
        if "." in last:
            stem, ext = last.rsplit(".", 1)
            return (bool(stem) and ext.isalnum()
                    and ext.lower() in [e[1:] for e in PATH_EXTS])
        return norm.endswith("/")
    # a bare filename: only if it has a known extension AND a stem
    if not tok.lower().endswith(PATH_EXTS):
        return False
    stem = tok.rsplit(".", 1)[0]
    return bool(stem) and re.search(r"[A-Za-z0-9_]", stem)


def group_paths():
    for rel in RECORDS:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        txt = read(rel)
        paras = paragraphs(txt)
        # github orgs used in URLs in this document -- their tokens are URLs
        gh = set()
        for m in re.finditer(r"https://github\.com/([\w.-]+/[\w.-]+)", txt):
            gh.add(m.group(1))
            gh.add(m.group(1).split("/")[0])
        for m in TOKEN_RE.finditer(txt):
            tok = m.group(1).strip()
            if not path_like(tok):
                continue
            if tok in gh or tok.split("/")[0] in gh:
                continue
            line = txt[:m.start()].count("\n") + 1
            para = para_at(paras, line)
            if any(e in para for e in EXEMPT):
                continue
            ok = False
            norm = tok.replace("\\", "/")
            if os.path.isabs(norm) or re.match(r"^[A-Za-z]:/", norm):
                ok = os.path.exists(norm)
            elif "/" in norm:
                for base in (ROOT, VD, os.path.dirname(ROOT)):
                    if os.path.exists(os.path.join(base, norm.replace("/", os.sep))):
                        ok = True
                        break
            else:
                for base in (ROOT, VD, os.path.dirname(ROOT)):
                    hit = False
                    for dirpath, dirnames, filenames in os.walk(base):
                        if tok in filenames:
                            hit = True
                            break
                        dirnames[:] = [d for d in dirnames
                                       if d not in (".git", "_build", "target")]
                    if hit:
                        ok = True
                        break
            check("%s:%d path exists: %s" % (os.path.basename(rel), line, tok), ok)


