        m = re.search(r"\*\*(\d+)\*\*\s+`DoubleML\*` estimator structs", txt)
        check("README Status table: estimator count is %d" % n,
              bool(m) and int(m.group(1)) == n,
              "README says %s" % (m.group(1) if m else "?"))


