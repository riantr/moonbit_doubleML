# 4. no mojibake
# ---------------------------------------------------------------------------
def group_mojibake():
    targets = list(RECORDS) + ["_verify/upstream_prove_1649/README.md",
                               "README.mbt.md"]
    for rel in targets:
        p = os.path.join(ROOT, rel.replace("/", os.sep))
        if not os.path.exists(p):
            continue
        raw = open(p, "rb").read()
        try:
            txt = raw.decode("utf-8")
        except UnicodeDecodeError as e:
            check("no mojibake: %s" % rel, False, "not valid UTF-8: %s" % e)
            continue
        bad = [c for c in ("\ufffd", "\u9225") if c in txt]
        check("no mojibake: %s" % rel, not bad, "markers %s" % bad if bad else "")


